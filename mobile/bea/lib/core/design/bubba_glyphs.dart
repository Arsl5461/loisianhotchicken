@immutable
class BubbaGlyph {
  const BubbaGlyph(this.width, this.height, this.data);

  final double width;
  final double height;
  final String data;

  Path pathFor(Size size) {
    final sx = size.width / width;
    final sy = size.height / height;
    final tokens = data.split(' ');
    final path = Path();
    var i = 0;
    double nx() => double.parse(tokens[i++]) * sx;
    double ny() => double.parse(tokens[i++]) * sy;
    while (i < tokens.length) {
      switch (tokens[i++]) {
        case 'M':
          path.moveTo(nx(), ny());
        case 'L':
          path.lineTo(nx(), ny());
        case 'C':
          path.cubicTo(nx(), ny(), nx(), ny(), nx(), ny());
        case 'Z':
          path.close();
      }
    }
    return path;
  }
}

