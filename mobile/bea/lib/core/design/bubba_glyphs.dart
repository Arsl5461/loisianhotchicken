class BubbaGlyphIcon extends StatelessWidget {
  const BubbaGlyphIcon(
    this.glyph, {
    super.key,
    required this.color,
    this.width,
    this.height,
    this.strokeWidth,
    this.dash,
    this.dashGap,
  });

  final BubbaGlyph glyph;
  final Color color;
  final double? width;
  final double? height;
  final double? strokeWidth;
  final double? dash;
  final double? dashGap;

  @override
  Widget build(BuildContext context) {
    final w = width ?? (height == null
        ? glyph.width
        : height! * glyph.width / glyph.height);
    final h = height ?? w * glyph.height / glyph.width;
    return CustomPaint(
      size: Size(d(w), d(h)),
      painter: _GlyphPainter(glyph, color, strokeWidth, dash, dashGap),
    );
  }
}

class _GlyphPainter extends CustomPainter {
  const _GlyphPainter(
    this.glyph,
    this.color,
    this.strokeWidth,
    this.dash,
    this.dashGap,
  );

  final BubbaGlyph glyph;
  final Color color;
  final double? strokeWidth;
  final double? dash;
  final double? dashGap;

  @override
  void paint(Canvas canvas, Size size) {
    final paint = Paint()..color = color;
    if (strokeWidth != null) {
      paint
        ..style = PaintingStyle.stroke
        ..strokeWidth = d(strokeWidth!)
        ..strokeCap = StrokeCap.round;
    }
    final path = glyph.pathFor(size);
    if (dash == null || strokeWidth == null) {
      canvas.drawPath(path, paint);
      return;
    }
    final on = d(dash!);
    final off = d(dashGap ?? dash!);
    for (final metric in path.computeMetrics()) {
      if (metric.length <= on) {
        canvas.drawPath(metric.extractPath(0, metric.length), paint);
        continue;
      }
      var start = 0.0;
      while (start < metric.length) {
        final end = math.min(start + on, metric.length);
        canvas.drawPath(metric.extractPath(start, end), paint);
        start = end + off;
      }
    }
  }

  @override
  bool shouldRepaint(_GlyphPainter old) =>
      old.color != color ||
      old.glyph != glyph ||
      old.strokeWidth != strokeWidth ||
      old.dash != dash ||
      old.dashGap != dashGap;
}
